async (page) => {
  if (!page.url().startsWith('http://127.0.0.1:5198/')) throw Error('Fixture only');
  const control = async data => page.request.post('http://127.0.0.1:18991/__test/control', { data });
  const state = async () => (await page.request.get('http://127.0.0.1:18991/__test/state')).json();
  const check = (ok, label) => { if (!ok) throw Error(label); };
  await control({ failSettings: false });
  await page.getByRole('button', { name: '写作偏好', exact: true }).click();
  const preview = page.getByRole('switch', { name: '生成后预览确认', exact: true });
  const initial = await state();
  const initialPreview = initial.user.preview_before_save;
  const initialIterations = initial.user.max_llm_iterations ?? 10;
  const save = page.locator('.ai-settings-footer').getByRole('button', { name: '保存设置' });
  check(await save.isDisabled(), 'Clean preferences should not require saving');
  await preview.click();
  check(await save.isEnabled(), 'Changed preferences must enable Save');
  await preview.click();
  check(await save.isDisabled(), 'Reverting a change must clear dirty state');
  const audit = page.getByRole('switch', { name: '自动审核', exact: true });
  if (await audit.isChecked()) await audit.click();
  await page.waitForFunction(() => document.querySelector('#aiSettings_auto_audit_min_score')?.disabled);
  check(await page.getByRole('spinbutton', { name: '自动审核最低分数' }).isDisabled(), 'Audit score must disable with audit');
  await audit.click();
  await preview.click();
  await page.getByRole('button', { name: '高级设置', exact: true }).click();
  await page.getByRole('spinbutton', { name: '最大 LLM 交互轮数' }).fill(String(initialIterations + 1));
  await page.getByRole('button', { name: '模型与连接', exact: true }).click();
  const model = page.locator('#ai-generation-model');
  const currentModel = await model.inputValue();
  const manualModel = `${currentModel}-manual`;
  await model.fill(manualModel);
  const modelSaved = page.waitForResponse(response => response.url().includes('/auth/me') && response.request().method() === 'PATCH');
  await model.press('Enter');
  await modelSaved;
  let saved = await state();
  check(saved.user.preferred_llm_model === manualModel, 'Enter must commit the model');
  check(saved.user.preview_before_save === initialPreview, 'Model Enter must not save preference drafts');
  check((saved.user.max_llm_iterations ?? 10) === initialIterations, 'Model Enter must not save advanced drafts');
  await page.getByRole('button', { name: '写作偏好', exact: true }).click();
  check(await preview.isChecked() !== initialPreview, 'Model changes must retain unsaved preference input');
  await control({ failSettings: true });
  await save.click();
  await page.getByRole('alert').filter({ hasText: '测试设置保存失败' }).waitFor();
  check(await preview.isChecked() !== initialPreview, 'Failed save must retain preference input');
  check(await save.isEnabled(), 'Failed save must remain retryable');
  await control({ failSettings: false });
  await save.click();
  await page.locator('.ai-settings-footer').getByRole('status').filter({ hasText: '所有修改已保存' }).waitFor();
  saved = await state();
  check(saved.user.preview_before_save !== initialPreview && saved.user.max_llm_iterations === initialIterations + 1, 'Save must apply drafts from both tabs');
  await page.getByRole('combobox', { name: 'AI 语言设置', exact: true }).click();
  await page.getByRole('option', { name: 'English', exact: true }).click();
  await save.click();
  await page.locator('.ai-settings-footer').getByRole('status').filter({ hasText: '所有修改已保存' }).waitFor();
  check((await state()).user.ai_language === 'en', 'Explicit AI language must persist');
  await page.getByRole('combobox', { name: 'AI 语言设置', exact: true }).click();
  await page.getByRole('option', { name: '跟随界面语言', exact: true }).click();
  await save.click();
  await page.locator('.ai-settings-footer').getByRole('status').filter({ hasText: '所有修改已保存' }).waitFor();
  check((await state()).user.ai_language === null, 'Follow UI language must be sent as null');
  await preview.click();
  await page.getByRole('button', { name: '返回作品库', exact: true }).click();
  const leave = page.getByRole('dialog', { name: '保存修改后再离开？' });
  await leave.waitFor();
  await leave.getByRole('button', { name: '留在此页', exact: true }).click();
  check(page.url().endsWith('/settings'), 'Stay must cancel navigation');
  await page.getByRole('button', { name: '返回作品库', exact: true }).click();
  await leave.getByRole('button', { name: '保存并离开', exact: true }).click();
  await page.waitForURL('http://127.0.0.1:5198/');
  check((await state()).user.preview_before_save === initialPreview, 'Save and leave must persist the final edit');
  return 'PASS: dirty/revert state, audit dependency, Enter commits only model, cross-tab draft retention, failed-save retry, language mapping, save-and-leave protection';
}
